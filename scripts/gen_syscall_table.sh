#!/bin/sh
# Regenerate internal/app/syscalls_<arch>.go from kernel UAPI headers.
# Requires the target arch's unistd header; run on the matching host.
set -eu
cd "$(dirname "$0")/.."

gen() {
	arch="$1"; header="$2"; out="internal/app/syscalls_${arch}.go"
	if [ ! -f "$header" ]; then
		echo "skip $arch: $header not found" >&2
		return
	fi
	{
		echo "// Code generated by scripts/gen_syscall_table.sh. DO NOT EDIT."
		echo "package app"
		echo ""
		echo "var syscallNames = map[uint32]string{"
		# x86_64: #define __NR_read 0 ; arm64 asm-generic: #define __NR_read 63
		grep -E '^#define __NR_[a-z0-9_]+[[:space:]]+[0-9]+' "$header" |
			sed -E 's/^#define __NR_([a-z0-9_]+)[[:space:]]+([0-9]+).*/\2: "\1",/' |
			sort -n | awk '!seen[$1]++'
		echo "}"
	} > "$out"
	echo "wrote $out"
}

gen amd64 /usr/include/x86_64-linux-gnu/asm/unistd_64.h
gen amd64 /usr/include/asm/unistd_64.h
gen arm64 /usr/include/asm-generic/unistd.h
